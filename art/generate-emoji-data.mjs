// Writes ../emoji_data_generated.go, the standard emoji a role's emoji
// picker offers, from the `unicode-emoji-json` package — the same package and
// version bridge-ui's chat picker is generated from.
//
//   cd art && npm ci && node generate-emoji-data.mjs
//
// Emoji newer than MAX_EMOJI_VERSION are left out: the fonts most readers have
// draw them as empty boxes. Skin-tone variants are left out too; the picker
// offers each emoji in its plain form.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const MAX_EMOJI_VERSION = 15.0
const require = createRequire(import.meta.url)
const groups = JSON.parse(readFileSync(require.resolve('unicode-emoji-json/data-by-group.json'), 'utf8'))
const packageVersion = JSON.parse(readFileSync(require.resolve('unicode-emoji-json/package.json'), 'utf8')).version

const lines = [
  '// Code generated by art/generate-emoji-data.mjs from unicode-emoji-json ' + packageVersion + ',',
  `// emoji version ${MAX_EMOJI_VERSION} and older. DO NOT EDIT; run the script.`,
  '',
  'package discordsignup',
  '',
  '// standardEmojiGroups are the standard emoji, in Unicode order, by group.',
  'var standardEmojiGroups = []standardEmojiGroup{',
]
let count = 0
for (const group of groups) {
  const emojis = group.emojis.filter(e => parseFloat(e.emoji_version) <= MAX_EMOJI_VERSION)
  if (emojis.length === 0) continue
  lines.push(`\t{Name: ${JSON.stringify(group.name)}, Emojis: []standardEmoji{`)
  for (const e of emojis) { lines.push(`\t\t{${JSON.stringify(e.emoji)}, ${JSON.stringify(e.name)}},`); count++ }
  lines.push('\t}},')
}
lines.push('}', '')
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'emoji_data_generated.go')
writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out}: ${count} emoji`)
